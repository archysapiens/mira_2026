/* Sistema MIRA V1 - Azure SQL Database */
SET NOCOUNT ON;
GO

IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name='mira') EXEC('CREATE SCHEMA mira');
GO

CREATE TABLE mira.Roles(
  RoleId TINYINT IDENTITY PRIMARY KEY,
  Code VARCHAR(20) NOT NULL UNIQUE,
  Name NVARCHAR(80) NOT NULL
);
CREATE TABLE mira.Users(
  UserId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY,
  Email NVARCHAR(320) NOT NULL UNIQUE,
  PasswordHash VARCHAR(64) NOT NULL,
  FullName NVARCHAR(180) NOT NULL,
  Phone NVARCHAR(30) NULL,
  Company NVARCHAR(180) NULL,
  RoleId TINYINT NOT NULL REFERENCES mira.Roles(RoleId),
  IsActive BIT NOT NULL DEFAULT 1,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  UpdatedAt DATETIME2 NULL
);
CREATE TABLE mira.Services(
  ServiceId INT IDENTITY PRIMARY KEY,
  Code VARCHAR(40) NOT NULL UNIQUE,
  Name NVARCHAR(180) NOT NULL,
  Description NVARCHAR(700) NULL,
  IsActive BIT NOT NULL DEFAULT 1
);
CREATE SEQUENCE mira.RequestFolioSequence AS BIGINT START WITH 1 INCREMENT BY 1;
CREATE TABLE mira.Requests(
  RequestId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY,
  Folio AS ('MIRA-'+CONVERT(char(4),DATEPART(year,CreatedAt))+'-'+RIGHT('000000'+CONVERT(varchar(6),FolioNumber),6)) PERSISTED,
  FolioNumber BIGINT NOT NULL DEFAULT NEXT VALUE FOR mira.RequestFolioSequence,
  ClientUserId UNIQUEIDENTIFIER NULL REFERENCES mira.Users(UserId),
  ContactName NVARCHAR(180) NOT NULL,
  Email NVARCHAR(320) NOT NULL,
  Phone NVARCHAR(30) NULL,
  Company NVARCHAR(180) NULL,
  Location NVARCHAR(300) NOT NULL,
  Need NVARCHAR(300) NULL,
  Urgency NVARCHAR(80) NULL,
  Description NVARCHAR(1500) NULL,
  Source VARCHAR(20) NOT NULL DEFAULT 'WEB',
  Status CHAR(1) NOT NULL DEFAULT 'E' CHECK(Status IN('E','A','C','T')),
  AssignedOperatorId UNIQUEIDENTIFIER NULL REFERENCES mira.Users(UserId),
  AssignedByUserId UNIQUEIDENTIFIER NULL REFERENCES mira.Users(UserId),
  AssignedAt DATETIME2 NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  UpdatedAt DATETIME2 NULL,
  CONSTRAINT UQ_Requests_Folio UNIQUE(FolioNumber)
);
CREATE TABLE mira.RequestServices(
  RequestId UNIQUEIDENTIFIER NOT NULL REFERENCES mira.Requests(RequestId),
  ServiceId INT NOT NULL REFERENCES mira.Services(ServiceId),
  PRIMARY KEY(RequestId,ServiceId)
);
CREATE TABLE mira.WorkNotes(
  WorkNoteId BIGINT IDENTITY PRIMARY KEY,
  RequestId UNIQUEIDENTIFIER NOT NULL REFERENCES mira.Requests(RequestId),
  UserId UNIQUEIDENTIFIER NOT NULL REFERENCES mira.Users(UserId),
  Note NVARCHAR(2000) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE TABLE mira.StatusHistory(
  StatusHistoryId BIGINT IDENTITY PRIMARY KEY,
  RequestId UNIQUEIDENTIFIER NOT NULL REFERENCES mira.Requests(RequestId),
  PreviousStatus CHAR(1) NULL,
  NewStatus CHAR(1) NOT NULL CHECK(NewStatus IN('E','A','C','T')),
  Comment NVARCHAR(700) NULL,
  ChangedByUserId UNIQUEIDENTIFIER NULL REFERENCES mira.Users(UserId),
  ChangedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE TABLE mira.Notifications(
  NotificationId BIGINT IDENTITY PRIMARY KEY,
  UserId UNIQUEIDENTIFIER NOT NULL REFERENCES mira.Users(UserId),
  RequestId UNIQUEIDENTIFIER NULL REFERENCES mira.Requests(RequestId),
  Title NVARCHAR(180) NOT NULL,
  Message NVARCHAR(600) NOT NULL,
  IsRead BIT NOT NULL DEFAULT 0,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_Requests_StatusCreated ON mira.Requests(Status,CreatedAt DESC);
CREATE INDEX IX_Requests_Client ON mira.Requests(ClientUserId,CreatedAt DESC);
CREATE INDEX IX_Requests_Operator ON mira.Requests(AssignedOperatorId,Status);
CREATE INDEX IX_WorkNotes_Request ON mira.WorkNotes(RequestId,CreatedAt DESC);
GO

